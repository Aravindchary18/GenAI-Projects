
from __future__ import annotations

import json
from typing import Any

from agents.mcp_client import (
    call_tool_sync,
    discover_tools_sync,
)

from agents.tool_registry import (
    TOOL_POLICIES,
    validate_tool_request,
)


MAX_TOOL_OUTPUT_CHARS = 12000


def build_llm_tool_schemas(
    catalogue: list[dict[str, Any]] | None = None,
):
    """Build function schemas only for allowlisted MCP tools."""

    discovered = (
        catalogue
        if catalogue is not None
        else discover_tools_sync()
    )

    if not isinstance(discovered, list):
        raise TypeError(
            "MCP discovery did not return a tool list."
        )

    schemas = []
    discovered_names = set()

    for item in discovered:

        if not isinstance(item, dict):
            continue

        name = str(item.get("name") or "").strip()

        if not name or name not in TOOL_POLICIES:
            continue

        policy = TOOL_POLICIES[name]

        raw_schema = item.get("input_schema") or {}

        raw_properties = raw_schema.get("properties") or {}

        if not isinstance(raw_properties, dict):
            raise ValueError(
                f"Invalid MCP schema for {name}."
            )

        properties = {
            key: value
            for key, value in raw_properties.items()
            if key in policy.allowed_arguments
        }

        # Approval IDs are never generated by the LLM.
        # The application injects them after database verification.
        if name == "send_gmail_draft_after_approval":
            properties.pop("approval_id", None)

        required = sorted(
            argument
            for argument in policy.required_arguments
            if argument in properties
        )

        missing = (
            set(policy.required_arguments)
            - set(properties)
        )

        if missing:
            raise ValueError(
                f"MCP schema for {name} is missing: "
                f"{', '.join(sorted(missing))}"
            )

        parameters = {
            "type": "object",
            "properties": properties,
            "required": required,
            "additionalProperties": False,
        }

        description = str(
            item.get("description") or ""
        ).strip()

        if policy.requires_approval:
            description += (
                " This action always pauses for user approval. "
                "The application adds the approval ID."
            )

        schemas.append({
            "type": "function",
            "function": {
                "name": name,
                "description": (
                    description
                    or f"Call the {name} MCP tool."
                ),
                "parameters": parameters,
            },
        })

        discovered_names.add(name)

    if not schemas:
        raise RuntimeError(
            "No allowlisted MCP tools were discovered."
        )

    return schemas, discovered, discovered_names


def _parse_tool_payload(
    result: dict[str, Any]
) -> dict[str, Any]:

    text = str(result.get("text") or "")

    try:
        parsed = json.loads(text)
    except (TypeError, json.JSONDecodeError):
        parsed = None

    if isinstance(parsed, dict):
        return parsed

    structured = result.get("structured_content")

    if isinstance(structured, dict):
        return structured

    return {}


def _verify_sensitive_result(
    tool_name: str,
    result: dict[str, Any],
) -> None:
    """Verify the actual result of sensitive operations."""

    payload = _parse_tool_payload(result)

    if (
        tool_name == "fill_public_form_fields"
        and payload.get("submitted") is not False
    ):
        raise RuntimeError(
            "Form filling was not verified as non-submitting."
        )

    if (
        tool_name == "create_gmail_draft"
        and payload.get("status") != "draft_created_not_sent"
    ):
        raise RuntimeError(
            "Gmail did not confirm an unsent draft."
        )

    if (
        tool_name == "send_gmail_draft_after_approval"
        and payload.get("status") != "sent_after_approval"
    ):
        raise RuntimeError(
            "Gmail did not confirm the approved send."
        )

    if (
        tool_name == "download_public_pdf"
        and payload.get("saved") is not True
    ):
        raise RuntimeError(
            "PDF download was not confirmed."
        )


def _check_explicit_intent(
    tool_name: str,
    user_request: str,
) -> None:
    """Check that the user actually requested the action."""

    policy = TOOL_POLICIES[tool_name]

    if (
        not policy.user_must_request_explicitly
        or not policy.explicit_request_terms
    ):
        return

    request = user_request.casefold()

    terms = set(policy.explicit_request_terms)

    if tool_name == "open_public_website":
        terms.update({
            "website",
            "web page",
            "site",
            "url",
        })

    elif tool_name == "create_gmail_draft":
        terms.update({
            "write to",
            "message",
            "mail",
        })

    if not any(term in request for term in terms):
        raise PermissionError(
            f"The user request does not clearly authorize "
            f"'{tool_name}'. Ask for confirmation."
        )


def execute_mcp_tool_call(
    tool_name: str,
    arguments: dict[str, Any],
    *,
    user_request: str,
    selected_document_ids: list[str] | None,
    discovered_tool_names: set[str],
    approval_id: str | None = None,
) -> dict[str, Any]:

    if not isinstance(arguments, dict):
        raise ValueError(
            "Tool arguments must be a JSON object."
        )

    clean_arguments = dict(arguments)

    # Reuse the documents selected in the frontend.
    if (
        tool_name == "search_uploaded_documents"
        and not clean_arguments.get("document_ids")
        and selected_document_ids
    ):
        clean_arguments["document_ids"] = list(
            selected_document_ids
        )

    # Only the trusted graph approval workflow supplies this.
    if tool_name == "send_gmail_draft_after_approval":

        if not approval_id:
            raise PermissionError(
                "Gmail sending requires verified approval."
            )

        clean_arguments["approval_id"] = approval_id

    policy, clean_arguments = validate_tool_request(
        tool_name,
        clean_arguments,
        discovered_tool_names=discovered_tool_names,
    )

    _check_explicit_intent(
        tool_name,
        user_request,
    )

    if policy.requires_approval and not approval_id:
        raise PermissionError(
            "This tool cannot run without workflow approval."
        )

    # Actual execution goes through MCP.
    result = call_tool_sync(
        tool_name,
        clean_arguments,
    )

    if not isinstance(result, dict):
        raise TypeError(
            "MCP client returned an invalid result."
        )

    _verify_sensitive_result(
        tool_name,
        result,
    )

    return result


def tool_result_text(
    result: dict[str, Any],
) -> str:
    """Prepare bounded results for the LLM."""

    text = str(result.get("text") or "").strip()

    if not text and result.get("structured_content") is not None:

        text = json.dumps(
            result["structured_content"],
            ensure_ascii=False,
            default=str,
        )

    if not text:
        text = (
            "The MCP tool completed but returned no text content."
        )

    return text[:MAX_TOOL_OUTPUT_CHARS]